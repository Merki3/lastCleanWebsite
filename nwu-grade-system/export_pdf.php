<?php
session_start();
require('fpdf.php'); // Load the FPDF library you just downloaded

// Database connection
$db_host = 'localhost';
$db_user = 'root';
$db_pass = '';
$db_name = 'grade_opening_system';
try {
    $pdo = new PDO("mysql:host=$db_host;dbname=$db_name;charset=utf8", $db_user, $db_pass);
} catch (PDOException $e) {
    die("Database connection failed.");
}

if (!isset($_GET['id'])) die("No request ID provided.");
$id = $_GET['id'];

// Fetch Request and Instructor Name
$stmt = $pdo->prepare("SELECT r.*, u.full_name FROM grade_opening_requests r JOIN users u ON r.instructor_id = u.username WHERE r.request_id = ?");
$stmt->execute([$id]);
$req = $stmt->fetch(PDO::FETCH_ASSOC);
if (!$req) die("Request not found.");

// Fetch Grading Periods
$stmt_p = $pdo->prepare("SELECT period FROM request_periods WHERE request_id = ?");
$stmt_p->execute([$id]);
$periods = $stmt_p->fetchAll(PDO::FETCH_COLUMN);
$per_text = implode(', ', $periods);

// Fetch Approvers
$stmt_a = $pdo->prepare("SELECT a.*, u.full_name, u.role FROM approvals a JOIN users u ON a.approver_user_id = u.username WHERE a.request_id = ?");
$stmt_a->execute([$id]);
$approvals = [];
while ($row = $stmt_a->fetch(PDO::FETCH_ASSOC)) {
    $approvals[$row['role']] = $row;
}

// Create the PDF layout
class PDF extends FPDF {
    function Header() {
        // Draw the University Logo (Ensure this path matches your folder structure)
        if(file_exists('assets/logo/nwu.png')) {
            $this->Image('assets/logo/nwu.png', 30, 10, 22);
        }
        $this->SetFont('Arial', 'B', 16);
        $this->Cell(0, 8, 'NORTHWESTERN UNIVERSITY', 0, 1, 'C');
        $this->SetFont('Arial', 'B', 11);
        $this->Cell(0, 6, 'REQUEST FORM FOR THE OPENING OF GRADE PORTAL', 0, 1, 'C');
        $this->Ln(15);
    }
    function Footer() {
        $this->SetY(-15);
        $this->SetFont('Arial', 'I', 8);
        $this->Cell(0, 10, 'Document Generated by NWU Grade Portal System  -  Page ' . $this->PageNo() . ' / {nb}', 0, 0, 'C');
    }
}

$pdf = new PDF();
$pdf->AliasNbPages();
$pdf->AddPage();

// Helper function to print a neat row
function addRow($pdf, $label, $value) {
    $pdf->SetFont('Arial', 'B', 10);
    $pdf->Cell(45, 8, $label . ':', 0, 0);
    $pdf->SetFont('Arial', '', 10);
    $pdf->MultiCell(0, 8, $value, 0, 'L');
}

// === Request Details Section ===
$pdf->SetFont('Arial', 'B', 11);
$pdf->SetFillColor(230, 230, 230);
$pdf->Cell(0, 8, '  Request Details (' . $req['request_id'] . ')', 1, 1, 'L', true);
$pdf->Ln(4);

addRow($pdf, 'Instructor Name', $req['full_name']);
addRow($pdf, 'College', $req['college']);
addRow($pdf, 'Academic Year', $req['academic_year']);
addRow($pdf, 'Course Code', $req['subject_code']);
addRow($pdf, 'Course Title', $req['subject_title']);
addRow($pdf, 'Section', $req['section']);
addRow($pdf, 'Calendar', $req['calendar']);
addRow($pdf, 'Periods', $per_text);
addRow($pdf, 'Date Submitted', date('F j, Y', strtotime($req['date_submitted'])));

$pdf->Ln(2);
$pdf->SetFont('Arial', 'B', 10);
$pdf->Cell(45, 8, 'Reason:', 0, 1);
$pdf->SetFont('Arial', '', 10);
$pdf->MultiCell(0, 6, $req['reason']);
$pdf->Ln(10);

// === Approvals & Signatures Section ===
$pdf->SetFont('Arial', 'B', 11);
$pdf->Cell(0, 8, '  Approvals & Signatures', 1, 1, 'L', true);
$pdf->Ln(6);

$dean = $approvals['dean'] ?? null;
$vpaa = $approvals['vpaa'] ?? null;

$pdf->SetFont('Arial', 'B', 10);
$pdf->Cell(95, 6, 'Recommended by (College Dean):', 0, 0);
$pdf->Cell(95, 6, 'Approved by (VPAA):', 0, 1);

$pdf->SetFont('Arial', '', 10);
$pdf->Cell(95, 8, $dean ? $dean['full_name'] : 'PENDING', 0, 0);
$pdf->Cell(95, 8, $vpaa ? $vpaa['full_name'] : 'PENDING', 0, 1);

$pdf->SetFont('Arial', 'I', 9);
$pdf->Cell(95, 5, $dean ? ($dean['decision'] ? 'Recommended on ' . date('M j, Y', strtotime($dean['decision_date'])) : 'Rejected') : '', 0, 0);
$pdf->Cell(95, 5, $vpaa ? ($vpaa['decision'] ? 'Approved on ' . date('M j, Y', strtotime($vpaa['decision_date'])) : 'Rejected') : '', 0, 1);

// === CICT Action Section ===
if (isset($approvals['cict'])) {
    $cict = $approvals['cict'];
    $pdf->Ln(10);
    $pdf->SetFont('Arial', 'B', 11);
    $pdf->Cell(0, 8, '  CICT Action Record', 1, 1, 'L', true);
    $pdf->Ln(4);
    addRow($pdf, 'Grades Opened By', $cict['full_name']);
    addRow($pdf, 'Access Granted On', date('F j, Y g:i A', strtotime($cict['decision_date'])));
    $exp = date('F j, Y g:i A', strtotime($cict['decision_date'] . ' +48 hours'));
    addRow($pdf, 'Access Expires On', $exp);
}

// Output the PDF to the browser
$pdf->Output('I', 'Request_' . $req['request_id'] . '.pdf');
?>